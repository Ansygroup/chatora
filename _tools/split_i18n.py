#!/usr/bin/env python3
"""Ship one small dictionary per language instead of every language everywhere.

assets/js/i18n.js + assets/js/i18n-pages.js stay the single source of truth
(the builders and the coverage gate read them), but together they weigh more
than 1 MB and used to be loaded by every page in every language even though
each page is already pre-rendered in its own language.

This final build step:
  * writes assets/js/i18n.<lang>.js for ar/es/fr/de/pt — just that language,
    base and page dictionaries merged;
  * points each /<lang>/ page at its own bundle;
  * removes the dictionaries from English pages entirely (English lives in
    the HTML; a legacy ?lang= URL is redirected to the static mirror before a
    dictionary is ever needed);
  * re-stamps asset versions.

Idempotent, and re-run by build.py on every build.
"""
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ("ar", "es", "fr", "de", "pt")
TAG = r'<script\b[^>]*\bsrc="(?:\.\./)?assets/js/%s(?:\?v=[0-9a-f]+)?"[^>]*>\s*</script>\s*'
BASE_TAG = re.compile(TAG % r"i18n\.js")
PAGES_TAG = re.compile(TAG % r"i18n-pages\.js")
BUNDLE_TAG = re.compile(TAG % r"i18n\.(?:ar|es|fr|de|pt)\.js")


def load_dictionaries():
    script = (
        "const fs=require('fs');global.window={};"
        "eval(fs.readFileSync('assets/js/i18n.js','utf8'));"
        "eval(fs.readFileSync('assets/js/i18n-pages.js','utf8'));"
        "const out={};"
        "for(const l of %s){out[l]=Object.assign({},(window.CHATORA_I18N||{})[l]||{},"
        "(window.CHATORA_I18N_PAGES||{})[l]||{});}"
        "process.stdout.write(JSON.stringify(out));" % json.dumps(list(LANGS))
    )
    result = subprocess.run(["node", "-e", script], cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit("split_i18n: could not evaluate the dictionaries with node\n" + result.stderr)
    return json.loads(result.stdout)


def write_bundles(dicts):
    for lang in LANGS:
        entries = dicts.get(lang) or {}
        if not entries:
            sys.exit("split_i18n: empty dictionary for %s" % lang)
        body = json.dumps({lang: entries}, ensure_ascii=False, separators=(",", ":"))
        # U+2028/2029 are legal in JSON but historically not in JS source.
        body = body.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
        text = (
            "/* generated by _tools/split_i18n.py from i18n.js + i18n-pages.js — do not edit */\n"
            "window.CHATORA_I18N=%s;window.CHATORA_I18N_PAGES={};\n" % body
        )
        path = os.path.join(ROOT, "assets", "js", "i18n.%s.js" % lang)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)


def rewrite(path, lang):
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    new = PAGES_TAG.sub("", src)
    new = BUNDLE_TAG.sub("", new)
    if lang:
        bundle = '<script defer="" src="../assets/js/i18n.%s.js"></script>\n' % lang
        new, count = BASE_TAG.subn(lambda _m: bundle, new, count=1)
        new = BASE_TAG.sub("", new)
        if count == 0 and "assets/js/main.js" in new:
            sys.exit("split_i18n: %s loads main.js but has no dictionary tag to replace" % path)
    else:
        new = BASE_TAG.sub("", new)
    if new != src:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new)
        return 1
    return 0


def main():
    write_bundles(load_dictionaries())
    changed = 0
    for path in sorted(glob.glob(os.path.join(ROOT, "*.html"))):
        changed += rewrite(path, None)
    for lang in LANGS:
        for path in sorted(glob.glob(os.path.join(ROOT, lang, "*.html"))):
            changed += rewrite(path, lang)
    sizes = ", ".join(
        "%s %d kB" % (lang, os.path.getsize(os.path.join(ROOT, "assets", "js", "i18n.%s.js" % lang)) // 1024)
        for lang in LANGS
    )
    print("i18n: per-language bundles written (%s) · %d pages rewired" % (sizes, changed))
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from stamp import run as stamp_run

    stamp_run()


if __name__ == "__main__":
    main()
